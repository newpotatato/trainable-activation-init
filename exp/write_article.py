def _groups(path):
    runs = load_runs(path)
    per_run_metrics(runs)
    g = defaultdict(list)
    for r in runs:
        g[(r["dataset"], r["act"], r["strategy"])].append(r)
    return g


def _paths_groups(paths):
    runs = []
    for path in paths:
        if os.path.exists(path):
            runs += load_runs(path)
    per_run_metrics(runs)
    g = defaultdict(list)
    for r in runs:
        g[(r["dataset"], r["act"], r["strategy"])].append(r)
    return g


