def vs_norm(doc):
    import numpy as np

    from summary_vs_norm import load as load_norm
    from summary_vs_norm import summarise

    g = load_norm()
    same = summarise(g, "default", np.random.default_rng(0))
    equal = summarise(g, "default_long", np.random.default_rng(0))

    def n(x, d=1):
        return f"{x:+.{d}f}".replace(".", ",").replace("-", "−")

    def rows(res):
        return [[ACT[r["act"]], f"{n(r['mean'])} [{n(r['lo'])}; {n(r['hi'])}]", n(r["median"], 2),
                 f"{r['not_worse']}/{r['tasks']}", f"{r['wins']}/{r['n']}", ptxt(r["p_holm"])] for r in res]

    by = {r["act"]: r for r in same}
    para(doc, "**Сводное сравнение с принятой нормой.** Чтобы оценить, не уступает ли выбор начальных значений "
              "стандартной инициализации в целом, пробный прогон длиной 5 эпох (стандартное значение включено в число "
              "кандидатов) сравнивался со стандартной инициализацией на всех 8 задачах сети 3 × 128 (4 основных "
              "набора данных × 5 seed и 4 гладкие задачи × 10 seed). Использованы две базы: стандартная инициализация "
              "при том же числе эпох обучения (30) и при равных суммарных затратах — 55 эпох, т. е. с добавлением тех "
              "эпох, которые пилот тратит на пробные прогоны. Для пары (задача, seed) вычисляется относительный "
              "выигрыш δ = (err_ст − err_пилот) / err_ст, где err — RMSE или 1 − доля верных ответов; эффект функции — "
              "среднее по задачам (каждая задача с одинаковым весом) с 95 %-м бутстреп-интервалом; приводится также "
              "медиана по задачам (табл. 8, рис. 8).")
    header = ["Функция", "Средний выигрыш, % [95 % ДИ]", "Медиана, %", "Задач не хуже", "Пар выиграно", "p (Холм)"]
    widths = [2.4, 4.2, 2.2, 2.2, 2.4, 2.2]
    table(doc, "Таблица 8а. Выигрыш пилота (5 эпох) относительно стандартной инициализации при одинаковом числе "
               "эпох обучения (30), все 8 задач", header, rows(same), size=9, col_widths=widths)
    table(doc, "Таблица 8б. То же при равных затратах: стандартная инициализация обучается 55 эпох", header,
          rows(equal), size=9, col_widths=widths)
    para(doc, f"При одинаковом числе эпох обучения пилот не уступает принятой норме ни для одной функции и значимо "
              f"превосходит её для PReLU ({by['prelu']['wins']} из {by['prelu']['n']} пар) и Swish-β "
              f"({by['swish']['wins']} из {by['swish']['n']}); для ACON-C и SigLin-T результаты сопоставимы, а "
              f"наибольшее отставание на отдельной задаче не превышает 3,1 %. Высокие средние значения для Swish-β и "
              f"SigLin-T в основном обусловлены задачей с синусоидами, где стандартная инициализация обучается плохо, "
              f"поэтому устойчивой оценкой типичного эффекта служит медиана — около +0,5 % для PReLU и Swish-β.")
    para(doc, "При равных затратах удлинённое обучение со стандартной инициализацией оказывается значимо лучше для "
              "всех функций. Основной вклад дают задачи, далёкие от сходимости: на Covertype оно выигрывает 15–23 %, "
              "на синусоидах — до 61 %; на задачах, где обучение сходится за 30 эпох (Wine Quality, Fashion-MNIST, "
              "Friedman #2), различия малы. Следовательно, при фиксированном бюджете обучения пробный прогон в среднем "
              "не хуже нормы, но его затраты оправданы, когда они не конкурируют с обучением самой модели, — "
              "например, если значения подбираются один раз и затем переиспользуются (перенос).")
    figure(doc, os.path.join(FIG, "fig8_vs_norm.png"),
           "Рис. 8. Выигрыш пилота (5 эпох) относительно стандартной инициализации при одинаковом числе эпох (слева) "
           "и при равных затратах (справа); серые маркеры — задачи, фиолетовые — среднее по задачам с 95 %-м "
           "доверительным интервалом; значения за пределами ±12 % прижаты к краю шкалы", width_cm=17)


