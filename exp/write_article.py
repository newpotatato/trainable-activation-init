def _err(r):
    return r["m"]["test"] if r["task"] == "reg" else 1 - r["m"]["test"]


def wins(g, act, st, ref_act=None, ref_st="default", datasets=DS):
    """Pairs (dataset x seed) where (act, st) beats (ref_act or act, ref_st); same weight seed."""
    w = n = 0
    for ds in datasets:
        base = {r["seed"]: _err(r) for r in g.get((ds, ref_act or act, ref_st), [])}
        other = {r["seed"]: _err(r) for r in g.get((ds, act, st), [])}
        for s in set(base) & set(other):
            n += 1
            w += other[s] < base[s]
    return w, n


def holm(pvals):
    """Holm-Bonferroni adjusted p-values (same order as input)."""
    order = sorted(range(len(pvals)), key=lambda i: pvals[i])
    adj, prev = [0.0] * len(pvals), 0.0
    for rank, i in enumerate(order):
        prev = max(prev, min(1.0, (len(pvals) - rank) * pvals[i]))
        adj[i] = prev
    return adj


def ptxt(p):
    return "< 0,001" if p < 0.001 else f"{p:.3f}".replace(".", ",")


def sign_table(g):
    """Rows: function; cells: wins/20 and Holm-adjusted p (correction over the 4 functions per strategy)."""
    cols = {}
    for st in ("random", "pilot", "transfer"):
        counts = [wins(g, a, st) for a in ACTS4]
        adj = holm([binomtest(w, n).pvalue for w, n in counts])
        cols[st] = [f"{w}/{n} (p = {ptxt(q)})" if q >= 0.001 else f"{w}/{n} (p {ptxt(q)})"
                    for (w, n), q in zip(counts, adj)]
    return [[ACT[a]] + [cols[st][i] for st in ("random", "pilot", "transfer")] for i, a in enumerate(ACTS4)]


