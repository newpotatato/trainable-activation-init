def build(results_writer, abstract_results, conclusion_writer, references):
    runs, g = stats()
    os.makedirs(OUT_DIR, exist_ok=True)
    doc = new_document()
    header(doc)
    global ABSTRACT
    ABSTRACT = ABSTRACT.format(abstract_results=abstract_results)
    intro(doc)
    method(doc)
    # main series = four base datasets without the pilot_d add-on; everything else is counted as additional
    setup_text_runs = sum(r["strategy"] != "pilot_d" and r["dataset"] in DS for r in runs)
    n_extra = len(runs) - setup_text_runs + sum(
        len(load_runs(os.path.join(HERE, "results", f)))  # load_runs skips failed (error) records
        for f in ("runs_mlp8.jsonl", "runs_pilot5.jsonl", "runs_pilot5b.jsonl", "runs_pilot5_mlp8.jsonl",
                  "runs_pilot_sweep.jsonl", "runs_default_long.jsonl", "runs_default_long_smooth.jsonl",
                  "runs_default_long_cw.jsonl")
        if os.path.exists(os.path.join(HERE, "results", f)))
    setup(doc)
    # fill the run count placeholder in the last setup paragraph
    for p in doc.paragraphs[::-1]:
        if "{n_runs}" in p.text:
            for r in p.runs:
                r.text = r.text.replace("{n_runs}", f"{setup_text_runs}").replace("{n_extra}", f"{n_extra}")
            break
    results_writer(doc, g)
    conclusion_writer(doc)
    heading(doc, "Литература")
    for i, ref in enumerate(references, 1):
        numbered(doc, ref, i, justify=False)
    doc.save(OUT)
    print("saved", OUT)


