def stats():
    runs = load_runs()
    per_run_metrics(runs)
    g = defaultdict(list)
    for r in runs:
        g[(r["dataset"], r["act"], r["strategy"])].append(r)
    return runs, g


def cell(g, ds, act, st):
    v = [r["m"]["test"] for r in g.get((ds, act, st), [])]
    if not v:
        return "—"
    return f"{np.mean(v):.4f} ± {np.std(v, ddof=1):.4f}" if len(v) > 1 else f"{v[0]:.4f}"


def wins(g, ds, act, st):
    err = lambda r: r["m"]["test"] if r["task"] == "reg" else 1 - r["m"]["test"]
    base = {r["seed"]: err(r) for r in g.get((ds, act, "default"), [])}
    other = {r["seed"]: err(r) for r in g.get((ds, act, st), [])}
    seeds = sorted(set(base) & set(other))
    return f"{sum(other[s] < base[s] for s in seeds)}/{len(seeds)}" if seeds else "—"


